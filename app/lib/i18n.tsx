const dictionaries: Record<Lang, Record<Key, string>> = { en: english, hi: hindi, mr: marathi }

const RISK: Record<string, Key> = { Low: 'riskLow', Moderate: 'riskModerate', High: 'riskHigh' }
const RISK_PHRASE: Record<string, Key> = { Low: 'lowRisk', Moderate: 'moderateRisk', High: 'highRisk' }
const STATUS: Record<string, Key> = { 'Needs review': 'statusNeedsReview', 'Follow-up': 'statusFollowUp', Synced: 'statusSynced', 'Saved Offline': 'statusSavedOffline' }
const REFERRAL: Record<string, Key> = { Pending: 'refPending', 'In review': 'refInReview', Completed: 'refCompleted' }
const PAIN: Record<string, Key> = { 'No pain': 'noPain', Mild: 'mild', Moderate: 'moderate', Severe: 'severe', Extreme: 'extreme' }
const SEX: Record<string, Key> = { Female: 'sexFemale', Male: 'sexMale', Other: 'sexOther' }
const PERIOD: Record<string, Key> = { '30 days': 'period30', '90 days': 'period90', '12 months': 'period12m' }
const SENSOR: Record<string, Key> = { Connected: 'connected', Measuring: 'measuringState' }
const OCCUPATION: Record<string, Key> = {
  'farm-labourer': 'occFarmLabourer', 'sugarcane-cutter': 'occSugarcaneCutter', farmer: 'occFarmer',
  'forest-gatherer': 'occForestGatherer', 'construction-worker': 'occConstructionWorker', homemaker: 'occHomemaker',
}

type ContextValue = {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: Key) => string
  /** Translate a key containing {placeholders} and substitute the given values. */
  tf: (key: Key, vars: Record<string, string | number>) => string
  L: (value: Localized) => string
  /** Enum-to-label helpers. The enum value itself (e.g. 'High') stays untouched in data. */
  risk: (value: string) => string
  riskPhrase: (value: string) => string
  status: (value: string) => string
  referral: (value: string) => string
  pain: (value: string) => string
  sex: (value: string) => string
  period: (value: string) => string
  sensor: (value: string) => string
  occupation: (slug: string) => string
  district: (id: string) => string
  /** Format an ISO date (YYYY-MM-DD) as a long date in the active language, Latin digits. */
  date: (iso: string) => string
}
const LangContext = createContext<ContextValue | null>(null)

const isLang = (value: unknown): value is Lang => typeof value === 'string' && (LANGS as readonly string[]).includes(value)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en')

  useEffect(() => {
    try { const saved = window.localStorage.getItem(STORAGE_KEY); if (isLang(saved)) setLangState(saved) } catch { /* storage unavailable */ }
    const onStorage = (event: StorageEvent) => { if (event.key === STORAGE_KEY && isLang(event.newValue)) setLangState(event.newValue) }
    window.addEventListener('storage', onStorage)
    return () => window.removeEventListener('storage', onStorage)
  }, [])

  const setLang = useCallback((next: Lang) => {
    setLangState(next)
    try { window.localStorage.setItem(STORAGE_KEY, next) } catch { /* storage unavailable */ }
  }, [])

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  const value = useMemo<ContextValue>(() => {
    const dict = dictionaries[lang]
    const t = (key: Key) => dict[key]
    const map = (table: Record<string, Key>) => (value: string) => (table[value] ? dict[table[value]] : value)
    return {
      lang, setLang, t,
      tf: (key, vars) => dict[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? '')),
      L: (value) => value[lang],
      risk: map(RISK), riskPhrase: map(RISK_PHRASE), status: map(STATUS), referral: map(REFERRAL), pain: map(PAIN),
      sex: map(SEX), period: map(PERIOD), sensor: map(SENSOR), occupation: map(OCCUPATION),
      date: (iso) => new Intl.DateTimeFormat(`${lang === 'en' ? 'en-IN' : lang === 'hi' ? 'hi-IN' : 'mr-IN'}-u-nu-latn`, { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(new Date(`${iso}T00:00:00Z`)),
      district: (id) => DISTRICTS.find((district) => district.id === id)?.name[lang] ?? id,
    }
  }, [lang, setLang])

  // React 19 hoists <title>/<meta> into <head>, so the document title and description follow the active language.
  return <LangContext.Provider value={value}><title>{dictionaries[lang].metaTitle}</title><meta name="description" content={dictionaries[lang].metaDescription} />{children}</LangContext.Provider>
}

export function useLang() {
  const value = useContext(LangContext)
  if (!value) throw new Error('useLang must be used within LanguageProvider')
  return value
}
export function L(value: Localized, lang: Lang) { return value[lang] }
export const DICTIONARIES = dictionaries
